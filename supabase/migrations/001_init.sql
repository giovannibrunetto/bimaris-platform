create or replace view public.analytics_daily as
select date_trunc('day', created_at) as day,
       count(*) as events,
       count(distinct anonymous_id) as users,
       count(distinct session_id) as sessions,
       count(*) filter (where event_name='page_view') as page_views,
       count(*) filter (where event_name in ('whatsapp_click','phone_click','website_click','directions_click')) as contact_actions
from public.analytics_events
group by 1
order by 1 desc;

create or replace view public.analytics_top_events_30d as
select event_name, count(*) as occurrences
from public.analytics_events
where created_at >= now() - interval '30 days'
group by event_name
order by occurrences desc;
